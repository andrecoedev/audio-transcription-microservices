/* eslint-env node */
// Run after journey.playwright.js (desktop and mobile) and server presentation.
// Only the disposable homologation stack on 4180/2029 is allowed.
async (page) => {
  const base = 'http://127.0.0.1:4180'
  const output = 'docs/design/design-system-shell'
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.context().route('**/*', route => {
    const origin = new URL(route.request().url()).origin
    return [base, 'http://127.0.0.1:2029'].includes(origin) ? route.continue() : route.abort()
  })
  const check = (value, message) => { if (!value) throw new Error(message) }
  const capture = async name => {
    await page.locator('main h1').first().waitFor()
    await page.evaluate(() => document.fonts.ready)
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${name}: horizontal overflow`)
    await page.screenshot({ path: `${output}/${name}.png`, fullPage: !name.startsWith('menu-') })
  }
  const login = async admin => {
    await page.goto(`${base}/login?${admin ? 'legacy=1&' : ''}returnTo=%2F`)
    await page.getByLabel(admin ? 'Usuário' : 'E-mail', { exact: true }).fill(admin ? 'synthetic-admin' : 'member@example.invalid')
    await page.getByLabel('Senha', { exact: true }).fill(admin ? 'Synthetic-only-passphrase!' : 'Synthetic-passphrase!')
    await page.getByRole('button', { name: 'Entrar', exact: true }).click()
    await page.waitForURL(`${base}/`)
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(base)
  await page.locator('main').waitFor()
  await page.getByRole('button', { name: 'Área da conta' }).click()
  const signOut = page.getByRole('button', { name: 'Sair', exact: true })
  if (await signOut.count()) await signOut.click()
  await page.evaluate(() => { localStorage.clear(); sessionStorage.clear() })
  await page.reload()
  await capture('home-guest-desktop')
  check(await page.getByRole('link', { name: 'Administração', exact: true }).count() === 0, 'Guest sees admin')
  await login(false)
  await capture('home-member-desktop')
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto(`${base}/transcriptions`)
  const original = page.getByRole('link', { name: 'Reunião sintética – integração.wav', exact: true })
  await original.waitFor()
  await capture('list-notebook')
  await original.click()
  await page.getByRole('heading', { name: 'Transcrição completa', exact: true }).waitFor()
  await capture('detail-notebook')
  await page.goto(`${base}/settings`)
  await page.getByRole('heading', { name: 'Serviços conectados', exact: true }).waitFor()
  await capture('settings-desktop')
  await page.setViewportSize({ width: 390, height: 844 })
  await capture('settings-mobile')
  const toggle = page.getByRole('button', { name: 'Abrir navegação', exact: true })
  await toggle.click()
  const drawer = page.getByRole('dialog', { name: 'Navegação principal' })
  await drawer.waitFor()
  check(await page.locator('main').evaluate(node => node.inert), 'Background not inert')
  check(await page.getByLabel('Fechar navegação pelo fundo').evaluate(node => getComputedStyle(node).backgroundColor !== 'rgba(0, 0, 0, 0)'), 'Backdrop is transparent')
  await capture('menu-member-mobile')
  await drawer.getByRole('button', { name: 'Área da conta' }).click()
  const last = drawer.getByRole('button', { name: 'Área da conta' })
  await last.focus()
  await page.keyboard.press('Tab')
  check(await drawer.evaluate(node => node.contains(document.activeElement)), 'Tab escaped drawer')
  await page.keyboard.press('Shift+Tab')
  check(await last.evaluate(node => node === document.activeElement), 'Reverse Tab did not wrap')
  await page.keyboard.press('Escape')
  await drawer.waitFor({ state: 'detached' })
  await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === 'Abrir navegação')
  check(await toggle.evaluate(node => node === document.activeElement), 'Focus not restored')
  await toggle.click()
  await drawer.getByRole('link', { name: 'Minhas transcrições', exact: true }).click()
  await page.waitForURL('**/transcriptions')
  await page.waitForFunction(() => document.activeElement === document.querySelector('main'))
  await capture('list-mobile')
  await page.setViewportSize({ width: 1440, height: 1000 })
  await login(true)
  await page.goto(`${base}/admin/settings`)
  await page.getByRole('heading', { name: 'Administração', exact: true, level: 1 }).waitFor()
  await capture('admin-desktop')
  check(await page.getByRole('link', { name: 'Administração', exact: true }).count() === 1, 'Admin section missing/duplicated')
  await page.setViewportSize({ width: 390, height: 844 })
  await capture('admin-mobile')
  await page.getByRole('button', { name: 'Abrir navegação', exact: true }).click()
  await capture('menu-admin-mobile')
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.getByRole('dialog').waitFor({ state: 'detached' })
  check(await page.locator('main').evaluate(node => !node.inert), 'Background stayed inert after resize')
  check(errors.length === 0, 'Unexpected JavaScript errors')
  return { screenshots: 11, widths: [1440, 1280, 390], focusTrap: true, focusReturn: true, destinationFocus: true, breakpointCleanup: true, javascriptErrors: errors }
}
