/* eslint-env node */
// After both synthetic journeys and server presentation. No provider generation.
async (page) => {
  const base = 'http://127.0.0.1:4180', api = 'http://127.0.0.1:2029'
  const output = 'docs/design/product-ux-copy'
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const config = await (await page.request.get(`${api}/auth/config`)).json()
  if (config.firebase_project_id !== 'usagi-beta-e2e') throw new Error('Synthetic project required')
  await page.context().route('**/*', route => [base, api].includes(new URL(route.request().url()).origin)
    ? route.continue() : route.abort())
  const capture = async name => {
    await page.evaluate(() => document.fonts.ready)
    if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error(`Overflow: ${name}`)
    await page.screenshot({ path: `${output}/${name}.png`, fullPage: false })
  }
  const login = async (admin, email = 'member@example.invalid') => {
    await page.goto(`${base}/login?${admin ? 'legacy=1&' : ''}returnTo=%2F`)
    await page.getByLabel(admin ? 'Usuário' : 'E-mail', { exact: true }).fill(admin ? 'synthetic-admin' : email)
    await page.getByLabel('Senha', { exact: true }).fill(admin ? 'Synthetic-only-passphrase!' : 'Synthetic-passphrase!')
    await page.getByRole('button', { name: 'Entrar', exact: true }).click()
    await page.waitForURL(`${base}/`)
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(base)
  await page.locator('main').waitFor()
  await page.getByRole('button', { name: 'Área da conta' }).click()
  const signOut = page.getByRole('button', { name: 'Sair', exact: true })
  if (await signOut.count()) await signOut.click()
  await page.reload()
  await page.getByRole('link', { name: 'Ver demonstração', exact: true }).waitFor()
  await capture('home-guest-desktop')
  await page.goto(`${base}/new-transcription`)
  await page.getByText('Dados de exemplo', { exact: true }).waitFor()
  await capture('demo-desktop')
  await page.goto(`${base}/signup`)
  await page.getByText(/Criar uma conta não concede automaticamente acesso ao Beta/).waitFor()
  await capture('signup-desktop')
  await login(false, 'other@example.invalid')
  await page.goto(`${base}/transcriptions`)
  await page.getByText('Você ainda não tem transcrições. Envie um áudio para criar a primeira.', { exact: true }).waitFor()
  await capture('empty-initial-desktop')
  await login(false)
  await page.getByRole('link', { name: 'Ver minhas reuniões' }).waitFor()
  await page.getByText('Fixture sintética longa.wav', { exact: true }).waitFor()
  await capture('home-member-desktop')
  await page.goto(`${base}/new-transcription`)
  await page.getByRole('button', { name: 'Transcrição do Beta', exact: true }).waitFor()
  await capture('upload-desktop')
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto(`${base}/transcriptions`)
  await page.getByRole('link', { name: 'Reunião sintética – integração.wav', exact: true }).waitFor()
  await capture('list-notebook')
  await page.getByPlaceholder('Buscar por nome do arquivo...').fill('Nenhum resultado de exemplo correspondente')
  await page.getByText('Nenhuma transcrição corresponde à busca.', { exact: true }).waitFor()
  await capture('empty-search-notebook')
  await page.goto(`${base}/transcriptions/1`)
  await page.getByRole('heading', { name: 'Transcrição completa', exact: true }).waitFor()
  await capture('transcription-notebook')
  await page.goto(`${base}/meetings/1`)
  await page.getByText('O grupo decidiu publicar', { exact: false }).first().waitFor()
  await capture('summary-notebook')
  const summaryTab = page.getByRole('tab', { name: 'Resumo', exact: true })
  await summaryTab.focus()
  await page.keyboard.press('ArrowRight')
  if (!(await page.getByRole('tab', { name: 'Tópicos', exact: true }).evaluate(node => node === document.activeElement && node.getAttribute('aria-selected') === 'true'))) throw new Error('Arrow navigation failed')
  await page.keyboard.press('End')
  if (!(await page.getByRole('tab', { name: 'Perguntas', exact: true }).evaluate(node => node === document.activeElement))) throw new Error('End navigation failed')
  await page.getByRole('tab', { name: 'Decisões', exact: true }).click()
  await capture('decisions-notebook')
  await page.getByRole('tab', { name: 'Tarefas', exact: true }).click()
  await page.getByRole('button', { name: 'Concluir', exact: true }).first().waitFor()
  await capture('tasks-notebook')
  await page.setViewportSize({ width: 390, height: 844 })
  await capture('meeting-mobile')
  await page.goto(`${base}/settings`)
  await page.getByRole('heading', { name: 'Serviços conectados', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Atualizar', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Conectar chave AssemblyAI', exact: true }).waitFor()
  await capture('settings-mobile')
  await page.getByRole('heading', { name: 'Serviços conectados', exact: true }).scrollIntoViewIfNeeded()
  await capture('settings-services-mobile')
  await page.setViewportSize({ width: 1440, height: 1000 })
  await capture('settings-desktop')
  await login(true)
  await page.goto(`${base}/admin/settings`)
  await page.getByRole('heading', { name: 'Administração', exact: true, level: 1 }).waitFor()
  await capture('admin-desktop')
  await page.setViewportSize({ width: 390, height: 844 })
  await capture('admin-mobile')
  if (errors.length) throw new Error('Unexpected JavaScript errors')
  return { screenshots: 18, widths: [1440, 1280, 390], tabsKeyboard: true, javascriptErrors: errors }
}
